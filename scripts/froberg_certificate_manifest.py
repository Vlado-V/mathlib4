#!/usr/bin/env python3
"""Generate/check small manifests for the unchanged Fröberg certificate files.

The script reads certificate bytes; it never writes to the certificate directory.
Only Python's standard library is required.  Generation writes two explicitly
named output files.  --check does not write any file.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys


SCHEMA = "froberg-certificate-inputs-v1"
SAFE_PATH = re.compile(r"[A-Za-z0-9_./-]+\Z")
LEAN_NAMESPACE = re.compile(r"[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*\Z")


def canonical_json(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()


def collect(root: Path, relative_data: Path) -> dict:
    if relative_data.is_absolute() or ".." in relative_data.parts:
        raise ValueError("--data-relative must be a relative path within --root")
    data = root
    for component in relative_data.parts:
        data = data / component
        if data.is_symlink():
            raise ValueError(f"certificate symlinks are not allowed: {data}")
    if not data.is_dir():
        raise ValueError(f"certificate directory does not exist: {data}")
    records = []
    for path in sorted(data.rglob("*"), key=lambda p: p.relative_to(root).as_posix()):
        if path.is_symlink():
            raise ValueError(f"certificate symlinks are not allowed: {path}")
        if path.is_dir():
            continue
        if not path.is_file():
            raise ValueError(f"non-regular certificate input: {path}")
        relative = path.relative_to(root).as_posix()
        if not SAFE_PATH.fullmatch(relative):
            raise ValueError(f"unsupported certificate path: {relative!r}")
        sha = hashlib.sha256()
        size = 0
        with path.open("rb") as stream:
            while block := stream.read(1024 * 1024):
                sha.update(block)
                size += len(block)
        records.append({"path": relative, "bytes": size, "sha256": sha.hexdigest()})
    if not records:
        raise ValueError("the certificate manifest must not be empty")
    payload = {"schema": SCHEMA, "data_directory": relative_data.as_posix(), "files": records}
    return {
        **payload,
        "aggregate_sha256": hashlib.sha256(canonical_json(payload)).hexdigest(),
        "file_count": len(records),
        "total_bytes": sum(record["bytes"] for record in records),
    }


def json_text(manifest: dict) -> str:
    return json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def lean_text(manifest: dict, namespace: str) -> str:
    entries = "\n".join(
        f"- `{record['path']}`\n"
        f"  {record['bytes']} bytes; SHA-256: `{record['sha256']}`"
        for record in manifest["files"]
    )
    return f'''/-
Copyright (c) 2026 Vlado Vojdanovski. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Vlado Vojdanovski
-/
module

public import Mathlib.Init

/-!
# Fröberg certificate input manifest

Generated by `scripts/froberg_certificate_manifest.py`; do not edit by hand.
This module identifies external data for source-cache invalidation. It asserts
no mathematical property of those data. The certificate checker must still
construct ordinary kernel-checked proofs of every required equation.

The build dependency target checks this manifest against all actual files
before compiling or reusing certificate-dependent modules.

## Inputs

{entries}
-/

@[expose] public section

namespace {namespace}

/-- Identity of the complete ordered certificate-input manifest. -/
def digest : String := "{manifest['aggregate_sha256']}"

/-- Number of ordinary files in the external certificate directory. -/
def fileCount : Nat := {manifest['file_count']}

/-- Combined byte length of the external certificate files. -/
def totalBytes : Nat := {manifest['total_bytes']}

end {namespace}
'''


def output_path(root: Path, value: str, data: Path) -> Path:
    path = Path(value)
    if not path.is_absolute():
        path = root / path
    path = path.resolve()
    if path == data or data in path.parents:
        raise ValueError("manifest outputs must not be inside the certificate directory")
    return path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--data-relative", "--data", dest="data", type=Path,
                        default=Path("certificates/finite"))
    parser.add_argument("--namespace", default="Froberg.CertificateManifest",
                        help="Lean namespace for the three manifest constants")
    parser.add_argument("--json", required=True, help="JSON manifest, relative to --root or absolute")
    parser.add_argument("--lean", required=True, help="Lean manifest, relative to --root or absolute")
    parser.add_argument("--check", action="store_true", help="Compare only; do not write")
    args = parser.parse_args()
    if not LEAN_NAMESPACE.fullmatch(args.namespace):
        raise ValueError("--namespace must be a dotted Lean namespace of ordinary identifiers")
    root = args.root.resolve(strict=True)
    data = (root / args.data).resolve(strict=True)
    if not data.is_relative_to(root):
        raise ValueError("certificate directory must remain inside --root")
    manifest = collect(root, args.data)
    outputs = [
        (output_path(root, args.json, data), json_text(manifest)),
        (output_path(root, args.lean, data), lean_text(manifest, args.namespace)),
    ]
    if outputs[0][0] == outputs[1][0]:
        raise ValueError("JSON and Lean outputs must be different files")
    if args.check:
        bad = [str(path) for path, text in outputs if not path.is_file() or
               path.read_text(encoding="utf-8") != text]
        if bad:
            print("Certificate manifest mismatch: " + ", ".join(bad), file=sys.stderr)
            print("Regenerate both manifests after an intentional data revision.", file=sys.stderr)
            return 1
        return 0
    for path, text in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"Generated certificate manifests: {manifest['file_count']} files, "
          f"{manifest['total_bytes']} bytes. Certificate files unchanged.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as error:
        print(f"Certificate manifest error: {error}", file=sys.stderr)
        raise SystemExit(2)
